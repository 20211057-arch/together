const { test } = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const Crew = require('../models/regularCrew');
const Post = require('../models/CrewPost');
const Photo = require('../models/CrewPhoto');
const router = require('../routes/crew/contentRouter');
const crewId = '111111111111111111111111';
const host = '222222222222222222222222';
const member = '333333333333333333333333';
const other = '444444444444444444444444';
test('crew content enforces membership, ownership and per-crew scope', async t => {
    t.mock.method(Crew, 'findById', async () => ({ host, member: { memberList: [{ user: host }, { user: member }] } }));
    const app = express();
    app.use(express.json());
    app.use((req,res,next) => { const id=req.get('X-Test-User'); if(id)req.user={_id:id}; next(); });
    app.use('/regular/:crewId/content', router);
    const server=app.listen(0,'127.0.0.1');
    await new Promise(resolve=>server.once('listening',resolve));
    t.after(()=>server.close());
    const url=`http://127.0.0.1:${server.address().port}/regular/${crewId}/content`;
    const request=(suffix,user,body)=>fetch(url+suffix,{method:'POST',headers:{'Content-Type':'application/json',...(user?{'X-Test-User':user}:{})},body:JSON.stringify(body||{})});
    const created=t.mock.method(Post,'create',async doc=>{assert.equal(doc.crew,crewId);assert.equal(doc.author,host);});
    assert.equal((await request('/posts',null)).status,401);
    assert.equal((await request('/posts',other)).status,403);
    assert.equal((await request('/posts',member,{title:'공지',content:'내용'})).status,403);
    assert.equal((await request('/posts',host,{title:' ',content:'내용'})).status,400);
    assert.equal((await request('/posts',host,{title:' 공지 ',content:' 내용 '})).status,200);
    assert.equal(created.mock.callCount(),1);
    t.mock.method(Post,'findOneAndUpdate',async query=>{assert.equal(query.crew,crewId);return null;});
    assert.equal((await request(`/posts/${other}/edit`,host,{title:'공지',content:'내용'})).status,404);
    t.mock.method(Photo,'findOneAndDelete',async query=>{assert.equal(query.crew,crewId);assert.equal(query.author,member);return null;});
    assert.equal((await request(`/photos/${other}/delete`,member)).status,404);
    assert.equal((await request('/photos',other)).status,403);
    const form = new FormData();
    form.append('photos',new Blob(['not an image'],{type:'image/png'}),'fake.png');
    const uploadResponse = await fetch(url+'/photos',{method:'POST',headers:{'X-Test-User':member},body:form});
    assert.equal(uploadResponse.status,400);
    assert.match((await uploadResponse.json()).message,/이미지/);
});
